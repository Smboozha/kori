// Расчёт итоговой концовки.
// n — число якорей, flags — набор флагов, door — выбранная дверь.
export function resolveEnding(n, flags, door) {
  const f = flags || {};
  // Насвай: игрок выбрасывал все банки -> амнезия.
  if ((f.nasvayThrown || 0) >= 3) return 8;
  // Отказ от себя: «Ты слабый» в слое 4 при достаточно собранном человеке.
  if (f.selfRefused && n >= 4) return 7;

  if (door === 'window') {
    if (n <= 1) return 1;                                    // Пусто
    if (f.gaveUpAct3 || n <= 2) return 2;                    // Тихий
    if (f.sisterRan && n <= 3) return 3;                     // Сестра
    if (n <= 5) return 4;                                    // Вместе
    return 6;                                                // Детдом
  }
  if (door === 'office') {
    if (n <= 1) return 1;                                    // Пусто
    if (n === 2) return f.sisterRan ? 3 : 2;                 // Сестра / Тихий
    if (n <= 4) return 5;                                    // После (ловушка)
    return 6;                                                // Детдом
  }
  // stay
  if (n <= 1) return 1;                                      // Пусто
  if (n <= 2) return 2;                                      // Тихий
  if (f.sisterRan && n <= 3) return 3;                       // Сестра
  if (n <= 3) return 4;                                      // Вместе
  if (n <= 4) return 5;                                      // После
  return 6;                                                  // Детдом
}

